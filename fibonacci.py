def generate_fibonacci(n):
    if n <= 0:
        return []
    elif n == 1:
        return [0]

    sequence = [0, 1]
    while len(sequence) < n:
        sequence.append(sequence[-1] + sequence[-2])
    return sequence

# Test the fibonacci program
terms = 10
print(f"First {terms} terms of Fibonacci sequence: {generate_fibonacci(terms)}")

